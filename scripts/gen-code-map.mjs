// Writes docs/code-map.md: one line per src/**/*.ts file (path, line count, first doc-comment line, exported names by
// kind). No file contents. Search this map before opening files to find an API. Usage: npm run map
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';

const ROOT = new URL('..', import.meta.url).pathname;
const SRC = join(ROOT, 'src');
const KINDS = [['function', 'fn'], ['class', 'class'], ['const', 'const'], ['interface', 'iface'], ['type', 'type']];

function* walk(dir) {
  for (const n of readdirSync(dir).sort()) {
    const p = join(dir, n);
    if (statSync(p).isDirectory()) yield* walk(p);
    else if (n.endsWith('.ts')) yield p;
  }
}

function describe(text) {
  const m = text.match(/\/\*\*?\s*\n?\s*\*?\s*([^\n*][^\n]*)/) ?? text.match(/^\/\/\s*(.+)$/m);
  const line = (m?.[1] ?? '').replace(/\*\/.*$/, '').trim();
  return line.length > 90 ? `${line.slice(0, 87)}...` : line;
}

function exportsOf(text) {
  const out = new Map(KINDS.map(([, k]) => [k, []]));
  for (const [kw, k] of KINDS) {
    const re = new RegExp(`^export\\s+(?:default\\s+)?(?:abstract\\s+)?(?:async\\s+)?${kw}\\s+([A-Za-z_$][\\w$]*)`, 'gm');
    for (const m of text.matchAll(re)) out.get(k).push(m[1]);
  }
  return [...out].filter(([, v]) => v.length).map(([k, v]) => `${k} ${v.join(', ')}`).join('; ');
}

const lines = ['# Code map (generated by `npm run map`, do not edit)', '', 'One line per file: `name (lines) description | exports by kind`. Search here before opening files.', ''];
let dir = '';
for (const f of walk(SRC)) {
  const rel = relative(ROOT, f);
  const d = rel.slice(0, rel.lastIndexOf('/'));
  if (d !== dir) { dir = d; lines.push(`## ${d}`); }
  const text = readFileSync(f, 'utf8');
  const n = text.split('\n').length - (text.endsWith('\n') ? 1 : 0);
  const desc = describe(text), ex = exportsOf(text);
  lines.push(`- ${rel.slice(d.length + 1)} (${n})${desc ? ' ' + desc : ''}${ex ? ' | ' + ex : ''}`);
}
writeFileSync(join(ROOT, 'docs/code-map.md'), lines.join('\n') + '\n');
console.log(`docs/code-map.md: ${lines.length} lines, ${lines.filter((l) => l.startsWith('- ')).length} files`);
